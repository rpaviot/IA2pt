@pytest.mark.parametrize("cfg", ["TATT", "NLA"])
def test_pp_limber_limit(ref, cfg):
    """Physics check of the ++ multipole expansion: for Pi_max -> infinity the
    eq. 19 projection of the xi_++ multipoles must reduce to the Limber form
    w_++ = (1/2pi) Int k dk [P_A J_0 + P_B J_4] (P_A = (P_EE + P_BB)/2,
    P_B = (P_EE - P_BB)/2), w_xx the same with P_B -> -P_B. TATT has P_BB != 0
    so it also tests the E/B split. The 3e-3 tolerance is the numerical floor
    of the eq. 19 route against the 2D fftlog (the w_gg path shows the same)."""
    from fastpt.misc import HT
    from scipy.interpolate import CubicSpline

    m = _model(ref, cfg, pimax=3000, dpi=0.25, rp_min_wedge=0)
    p = _pars(ref, cfg)
    rp = np.geomspace(1.0, 60.0, 12)
    wpp, wxx = m.compute_wpp(rp, *p), m.compute_wxx(rp, *p)
    pk_ee, pk_bb = m._pk_ii()
    a = 1.0 / (1.0 + m.zeff)
    P_EE = m.h**3 * pk_ee(m.ks, a, m.cosmo)
    P_BB = m.h**3 * pk_bb(m.ks, a, m.cosmo)
    r, w0 = HT.k_to_r(m.k, 0.5 * (P_EE + P_BB), 1.0, -1.0, 0.0, 1.0 / (2 * np.pi))
    _, w4 = HT.k_to_r(m.k, 0.5 * (P_EE - P_BB), 1.0, -1.0, 4.0, 1.0 / (2 * np.pi))
    w0, w4 = CubicSpline(r, w0)(rp), CubicSpline(r, w4)(rp)
    if cfg == "TATT":
        assert np.max(P_BB / P_EE) > 0.05
    np.testing.assert_allclose(wpp, w0 + w4, rtol=3e-3)
    # w_xx crosses zero: absolute tolerance scaled by w_++
    np.testing.assert_allclose(wxx, w0 - w4, atol=3e-3 * np.abs(wpp).max())
