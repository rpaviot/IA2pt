@pytest.mark.parametrize("cfg", ["TATT", "NLA"])
def test_no_wedge_cut_and_evolve_bias(ref, cfg):
    p = _pars(ref, cfg)
    m = _model(ref, cfg, rp_min_wedge=None)
    np.testing.assert_allclose(m.compute_xi_gg_wedge_monopole(ref["s_mid"], *p), ref[f"{cfg}_pt_nocut_xi0e"], rtol=RTOL)
    np.testing.assert_allclose(m.compute_xi_gi_wedge_quadrupole(ref["s_mid"], *p), ref[f"{cfg}_pt_nocut_xi2p"], rtol=RTOL)
    m = _model(ref, cfg, evolve_bias=True)
    np.testing.assert_allclose(m.compute_xi_gg_wedge_monopole(ref["s_mid"], *p), ref[f"{cfg}_pt_evb_xi0e"], rtol=RTOL)
    np.testing.assert_allclose(m.compute_wgp(ref["rp_mid"], *p), ref[f"{cfg}_pt_evb_wgp"], rtol=RTOL)


def test_ia_block_at_pair_redshift(ref):
    m = _model(ref, "NLA", z=ref["z_eff_IA"])
    np.testing.assert_allclose(m.compute_xi_gi_wedge_quadrupole(ref["s_mid"], *_pars(ref, "NLA")),
                               ref["NLA_pt_zia_xi2p"], rtol=RTOL)


def test_parameter_cache_and_sign(ref):
    """Changing a1 must refresh the spectra; positive a1 (radial alignment,
    e_+ = -e_t) gives POSITIVE xi~_{2,2} and w_g+ in this convention."""
    m = _model(ref, "NLA")
    p = list(_pars(ref, "NLA"))
    q2 = m.compute_xi_gi_wedge_quadrupole(ref["s_mid"], *p)
    wgp = m.compute_wgp(ref["rp_mid"], *p)
    assert np.all(q2 > 0) and np.all(wgp > 0)
    p[2] = -p[2]
    np.testing.assert_allclose(m.compute_xi_gi_wedge_quadrupole(ref["s_mid"], *p), -q2, rtol=1e-8)


def test_no_rsd_limits(ref):
    """do_rsd=False -> beta = 0: xi~_{2,2} is the pure xi^{2,2} term."""
    m = _model(ref, "NLA", do_rsd=False)
    p = _pars(ref, "NLA")
    m.compute_xi_gi_wedge_quadrupole(ref["s_mid"], *p)
    assert m._beta(m.f, p[0]) == 0.0
    m_rsd = _model(ref, "NLA")
    q_rsd = m_rsd.compute_xi_gi_wedge_quadrupole(ref["s_mid"], *p)
    q_real = m.compute_xi_gi_wedge_quadrupole(ref["s_mid"], *p)
    # RSD enhance the quadrupole amplitude by ~ (1 + beta/7) at large s
    assert np.all(np.abs(q_rsd[-5:]) > np.abs(q_real[-5:]))


